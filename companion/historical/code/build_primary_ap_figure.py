"""Build the manuscript TikZ figure from the unchanged locked contrast CSV.

Run with Python from any working directory, then compile the manuscript.
The generated fragment inherits IEEEtran's 8-point Times-style font.
"""
import csv
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'tables/primary_contrasts.csv'
with source.open(encoding='utf-8', newline='') as stream:
    rows = [r for r in csv.DictReader(stream) if r['metric'] == 'entry_average_precision']
records = {(r['contrast'], r['family'], r['surface']): r for r in rows}
families = [('xgboost', 'XGBoost'), ('lightgbm', 'LightGBM'), ('catboost', 'CatBoost')]
panels = [
    ('S6-S2', '(a) Pedigree beyond recent history'),
    ('S6-S3', '(b) Graph versus simple pedigree'),
    ('S7-M2', '(c) Pedigree beyond history and market'),
    ('S7-S6', '(d) Adding odds and popularity'),
]
assert len(rows) == len(records) == 36
assert {(c, f, s) for c, _ in panels for f, _ in families for s in ('turf', 'dirt')} <= set(records)

lines = [
    '% Generated by figures/build_primary_ap_figure.py; do not hand-edit data coordinates.',
    '% Locked source SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
    r'\begin{tikzpicture}[x=1pt,y=1pt,every node/.style={font=\footnotesize,inner sep=0pt}]',
    r'\useasboundingbox (0,-19) rectangle (510,259);',
    r'\fill[blue!70!black] (211,254) circle (1.8pt);',
    r'\node[anchor=west] at (217,254) {Turf};',
    r'\fill[red!70!black] (261,252.2) rectangle (264.6,255.8);',
    r'\node[anchor=west] at (270,254) {Dirt};',
]
for index, (contrast, title) in enumerate(panels):
    x0 = (index % 2) * 266
    y0 = 122 - (index // 2) * 122
    lo, hi = [(-0.015, 0.045), (-0.015, 0.045), (-0.004, 0.004), (-0.005, 0.13)][index]
    ticks = [[-0.01, 0, 0.02, 0.04], [-0.01, 0, 0.02, 0.04], [-0.004, -0.002, 0, 0.002, 0.004], [0, 0.04, 0.08, 0.12]][index]
    def xpos(value):
        return x0 + 55 + (float(value) - lo) / (hi - lo) * 181
    display = {'S6-S2':'C--A','S6-S3':'C--B','S7-M2':'E--D','S7-S6':'E--C'}[contrast]
    lines += [
        f'\\node[anchor=west,font=\\footnotesize\\bfseries] at ({x0},{y0+112}) {{{title}}};',
        f'\\node[anchor=west] at ({x0},{y0+100}) {{{display}}};',
        f'\\draw[gray,dashed] ({xpos(0):.5f},{y0+13}) -- ({xpos(0):.5f},{y0+91});',
    ]
    for family_index, (family, label) in enumerate(families):
        y = y0 + 82 - family_index * 27
        lines.append(f'\\node[anchor=west] at ({x0},{y-4.5}) {{{label}}};')
        for surface, offset, color in [('turf', 0, 'blue!70!black'), ('dirt', -9, 'red!70!black')]:
            row = records[contrast, family, surface]
            lower, estimate, upper = [float(row[k]) for k in ('ci95_lower', 'estimate', 'ci95_upper')]
            assert lo <= lower <= estimate <= upper <= hi, row
            py, px = y + offset, xpos(estimate)
            lines.append(f'\\draw[{color},line width=0.8pt] ({xpos(lower):.5f},{py}) -- ({xpos(upper):.5f},{py});')
            if surface == 'turf':
                lines.append(f'\\fill[{color}] ({px:.5f},{py}) circle (1.8pt);')
            else:
                lines.append(f'\\fill[{color}] ({px-1.8:.5f},{py-1.8:.1f}) rectangle ({px+1.8:.5f},{py+1.8:.1f});')
    lines.append(f'\\draw[gray] ({xpos(lo):.5f},{y0+11}) -- ({xpos(hi):.5f},{y0+11});')
    for tick in ticks:
        x = xpos(tick)
        text = '0' if tick == 0 else f'{tick:.{3 if index == 2 else 2}f}'.replace('-', r'\textminus{}')
        lines += [f'\\draw[gray] ({x:.5f},{y0+11}) -- ({x:.5f},{y0+8});',
                  f'\\node[anchor=north] at ({x:.5f},{y0+5}) {{{text}}};']
lines += [r'\node at (255,-16) {Difference in average precision (first setting minus second setting)};',
          r'\end{tikzpicture}']
(root.parent / 'paper/figures/primary_ap_contrasts.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Generated 24 AP estimates and 95% intervals from', source)
